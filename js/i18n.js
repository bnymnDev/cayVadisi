let lang = 'de';
export function setLang(l) { lang = STRINGS[l] ? l : 'de'; }
export function getLang() { return lang; }
export function t(key, ...args) {
  const v = STRINGS[lang][key] ?? STRINGS.de[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
export function tUpgrade(id) { return STRINGS[lang].upgradeNames[id]; }

// data-i18n im DOM anwenden
export function applyDom() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.innerHTML = t(el.dataset.i18n);
  });
  document.getElementById('controls-hint').innerHTML = t('controlsHint');
  document.documentElement.lang = lang;
}
